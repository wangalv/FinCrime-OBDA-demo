"""Ask Ontop about the AML typology (AMLO schema + AMLTRIX content) and check it against rdflib.

Two routes, same SPARQL, same answers expected:
  merged  AMLO (TBox) and data/amltrix.ttl (facts) merged into one file given to Ontop with -t.
          Ontop reads the facts from the ontology file and reasons over them (subclass, inverseOf, ...).
  aligned like csv, with the alignment facts (what each indicator needs, which data terms exist) added to the -t file; see src/typology.py
  csv     AMLO as -t; the individuals come from the AMLTRIX CSVs through the R2RML mapping
          generated/amltrix.r2rml.ttl (DuckDB reads the CSVs, in memory).

Run with the project venv:  .venv/bin/python src/typology_ontop.py [merged|csv|both]
The "gold" for each question is rdflib on data/amltrix.ttl with the direct (no-inference) pattern.
"""
import csv
import io
import subprocess
import sys
import tempfile
import time
from pathlib import Path

from rdflib import Graph

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paths  # noqa: E402

ROOT = paths.ROOT
AMLO = paths.AMLO
ABOX = paths.TYPOLOGY_ABOX
DECLARATIONS = paths.TYPOLOGY_ADAPTER
MERGED = paths.TYPOLOGY_MERGED
ALIGNMENT = paths.ALIGNMENT   # generated by src/typology.py
TBOX = paths.TYPOLOGY_TBOX
EMPTY_MAPPING = paths.TYPOLOGY_EMPTY_MAPPING
CSV_MAPPING = paths.TYPOLOGY_CSV_MAPPING
PROPS = paths.ONTOP_MEMORY_PROPS

PREFIXES = """PREFIX amlo: <https://example.org/amlo#>
PREFIX skos: <http://www.w3.org/2004/02/skos/core#>
PREFIX dct:  <http://purl.org/dc/terms/>
PREFIX amx:  <https://example.org/amltrix/>
"""

# (id, question, query for Ontop, query for rdflib gold or None when it is the same)
QUESTIONS = [
    ("Q1", "techniques and sub-techniques per tactic",
     """SELECT ?tactic (COUNT(DISTINCT ?t) AS ?n) WHERE {
          ?tac a amlo:Tactic ; skos:prefLabel ?tactic ; amlo:isAchievedBy ?t . } GROUP BY ?tactic ORDER BY ?tactic""", None),
    ("Q4", "data sources that can reveal the most techniques (all)",
     """SELECT ?source (COUNT(DISTINCT ?t) AS ?n) WHERE {
          ?ds a amlo:DataSource ; skos:prefLabel ?source . ?t amlo:isIdentifiedIn ?ds . } GROUP BY ?source ORDER BY ?source""", None),
    # regex flags go inline ("(?i)"): Ontop 5.5.0 does not support the 3-argument regex() on DuckDB (REGEXP_LIKE3)
    ("Q6", "techniques with indicators that mention round-trip / circular / funnel",
     """SELECT ?id ?name (COUNT(?i) AS ?n) WHERE {
          ?t skos:notation ?id ; skos:prefLabel ?name ; amlo:isIndicatedBy ?i . ?i skos:definition ?d .
          FILTER regex(?d, "(?i)round[- ]trip|circular|funnel") } GROUP BY ?id ?name ORDER BY ?id""", None),
    ("Q7", "ids that name more than one technique",
     """SELECT ?id (COUNT(?t) AS ?n) WHERE { ?t a amlo:Technique ; skos:notation ?id ; skos:prefLabel ?name .
          } GROUP BY ?id HAVING (COUNT(?t) > 1)""", None),
    # reasoning: the question uses the inverse property / the super-class, the gold uses the stored direction / both classes
    ("R1", "[inverseOf] tactics per technique via amlo:achievesTactic",
     """SELECT ?id ?tactic WHERE { ?t skos:notation ?id ; amlo:achievesTactic ?tac . ?tac skos:prefLabel ?tactic . } ORDER BY ?id ?tactic""",
     """SELECT ?id ?tactic WHERE { ?tac amlo:isAchievedBy ?t . ?t skos:notation ?id . ?tac skos:prefLabel ?tactic . } ORDER BY ?id ?tactic"""),
    ("R2", "[subClassOf] how many techniques, sub-techniques included, asked as amlo:Technique",
     """SELECT (COUNT(DISTINCT ?t) AS ?n) WHERE { ?t a amlo:Technique }""",
     """SELECT (COUNT(DISTINCT ?t) AS ?n) WHERE { { ?t a amlo:Technique } UNION { ?t a amlo:SubTechnique } }"""),
    ("R3", "[inverseOf] indicators of T0039 asked as amlo:indicates",
     """SELECT ?ind WHERE { ?i amlo:indicates amx:T0039 ; skos:prefLabel ?ind . } ORDER BY ?ind""",
     """SELECT ?ind WHERE { amx:T0039 amlo:isIndicatedBy ?i . ?i skos:prefLabel ?ind . } ORDER BY ?ind"""),
]


def build_merged():
    MERGED.parent.mkdir(exist_ok=True)
    if MERGED.exists() and MERGED.stat().st_mtime >= max(AMLO.stat().st_mtime, ABOX.stat().st_mtime, DECLARATIONS.stat().st_mtime):
        return
    g = Graph().parse(AMLO)
    g.parse(DECLARATIONS)
    g.parse(ABOX)
    g.serialize(MERGED, format="turtle")


def build_tbox():
    """AMLO + property declarations + alignment facts, for the route where the AMLTRIX content comes from the CSV mapping."""
    TBOX.parent.mkdir(exist_ok=True)
    srcs = [AMLO, DECLARATIONS, ALIGNMENT]
    if TBOX.exists() and TBOX.stat().st_mtime >= max(x.stat().st_mtime for x in srcs):
        return
    g = Graph()
    for x in srcs:
        g.parse(x)
    g.serialize(TBOX, format="turtle")


def rel(path):
    """Ontop is run from the repository root with relative paths (an absolute path with a space in it is not read)."""
    return str(Path(path).relative_to(ROOT))


def run_ontop(sparql, route):
    """Return (rows as lists of strings, seconds, error)."""
    if route == "merged":
        build_merged()
        args = ["-m", rel(EMPTY_MAPPING), "-t", rel(MERGED)]
    elif route == "aligned":
        build_tbox()
        args = ["-m", rel(CSV_MAPPING), "-t", rel(TBOX)]
    else:
        args = ["-m", rel(CSV_MAPPING), "-t", rel(AMLO)]
    with tempfile.TemporaryDirectory() as d:
        q, o = Path(d) / "q.rq", Path(d) / "out.csv"
        q.write_text(PREFIXES + sparql, encoding="utf-8")
        t = time.time()
        p = subprocess.run([str(ROOT / "tools" / "ontop.sh"), "query", *args, "-p", rel(PROPS), "-q", str(q), "-o", str(o)],
                           cwd=ROOT, capture_output=True, text=True)
        secs = time.time() - t
        if p.returncode != 0 or not o.exists():
            return None, secs, (p.stdout + p.stderr)[-500:]
        rows = list(csv.reader(io.StringIO(o.read_text(encoding="utf-8"))))
        return rows[1:], secs, None


def gold(sparql):
    global _g
    if _g is None:
        _g = Graph().parse(ABOX)
    return [[str(x) for x in r] for r in _g.query(PREFIXES + sparql)]


_g = None


def compare(route):
    out = []
    for qid, text, q_ontop, q_gold in QUESTIONS:
        want = gold(q_gold or q_ontop)
        got, secs, err = run_ontop(q_ontop, route)
        if err:
            out.append((qid, text, "ERROR", len(want), None, secs, err))
            continue
        same = sorted(got) == sorted(want)
        out.append((qid, text, "same" if same else "DIFF", len(want), len(got), secs, None))
    return out


def main():
    routes = ["merged", "csv"] if (sys.argv[1:] or ["both"])[0] == "both" else [sys.argv[1]]
    bad = 0
    for route in routes:
        if route == "csv" and not CSV_MAPPING.exists():
            print("csv route: generated/amltrix.r2rml.ttl not written yet")
            continue
        print(f"\n== route: {route}")
        for qid, text, status, n_gold, n_got, secs, err in compare(route):
            bad += status != "same"
            print(f"{qid:3} {status:5} gold rows {n_gold:>4}  ontop rows {n_got if n_got is not None else '-':>4}  {secs:4.1f}s  {text}")
            if err:
                print("    " + err.replace("\n", "\n    ")[:400])
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
