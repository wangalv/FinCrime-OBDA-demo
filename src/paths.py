"""Where every knowledge, mapping and validation file lives: ONE place, so a later move of the directory tree changes only this file.

The semantic layer is six modules (see docs/solution_design.pdf and CLAUDE.md). Ontop must be run from the repository root with paths relative to it
and without a space in them, so use rel() for anything handed to Ontop.

  1  External knowledge        the published typology: AMLO, the typology data (CSV, not edited), the adapter that makes Ontop read it
  2  AML core ontology         AML terms (amd:), independent of any database and any typology
  3  Typology requirements     what each indicator needs, where each term is recorded (data source), what background to show
  4  Data semantic / alignment the source vocabulary of our tables (fcd:) and the alignment (bridge) from it to the AML terms
  5  OBDA mapping              R2RML mappings, the lens, the database connection
  6  Validation                SHACL shapes, the indicator registry
  runtime                      small files the code reads to name variables; generated files (never edited by hand)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ONTOLOGY_DIR = ROOT / "ontology"       # modules 1 to 4: ontologies (AMLO stays at ontology/amlo.ttl: the older part of the repository uses it)
MAPPINGS_DIR = ROOT / "mappings"       # module 5: R2RML mappings and lenses
CONFIG_DIR = ROOT / "config" / "ontop" # module 5: the Ontop connection files
SHAPES_DIR = ROOT / "shapes"           # older part only: amlo-shapes.ttl
VALIDATION_DIR = ROOT / "validation"   # module 6: SHACL shapes and the indicator registry
MAPPING_DIR = ROOT / "mapping"         # only query_vars.ttl is left here (runtime helper)
GEN = ROOT / "generated"
TOOLS = ROOT / "tools"                 # Ontop CLI and JDK (git-ignored) and ontop.sh

# ---- 1  External knowledge
AMLO = ROOT / "ontology" / "amlo.ttl"                                   # also used by the older part of the repository: do not move
TYPOLOGY_CSV_DIR = ROOT / "vendor" / "amltrix"                          # published CSV files, not edited
TYPOLOGY_ADAPTER = ONTOLOGY_DIR / "external" / "amltrix" / "typology_adapter.ttl"                 # makes Ontop read a few standard properties (formerly typology_declarations.ttl)
TYPOLOGY_CSV_MAPPING = GEN / "amltrix.r2rml.ttl"                          # GENERATED by src/build_amltrix_mapping.py
TYPOLOGY_EMPTY_MAPPING = MAPPINGS_DIR / "typology" / "typology_none.r2rml.ttl"        # an empty mapping, for the route where the typology is passed as ontology
TYPOLOGY_ABOX = ROOT / "data" / "amltrix.ttl"                           # older route: the typology as triples

# ---- 2  AML core ontology
AML_CORE = ONTOLOGY_DIR / "core" / "aml_core.ttl"

# ---- 3  Typology requirements
TYPOLOGY_REQUIREMENTS = ONTOLOGY_DIR / "application" / "typology_requirements.ttl"       # needsTerm, backgroundTerm, recordedIn

# ---- 4  Data semantic / alignment
SOURCE_VOCABULARY = ONTOLOGY_DIR / "alignment" / "source_vocabulary.ttl"               # fcd: terms of our two tables
DATA_ALIGNMENT = ONTOLOGY_DIR / "alignment" / "aml_data_alignment.ttl"                 # the bridge: fcd: term is a kind of amd: term

# ---- 5  OBDA mapping
TX_MAPPING = MAPPINGS_DIR / "transaction" / "tx_features.r2rml.ttl"                      # transfers (table tx) and the accounts in them
CUSTOMER_MAPPING = MAPPINGS_DIR / "customer" / "customer.r2rml.ttl"                   # synthetic customer profiles (table kyc)
DATA_MAPPINGS = [TX_MAPPING, CUSTOMER_MAPPING]                          # Ontop takes ONE mapping: they are merged into DATA_MAPPING_MERGED
LENS = MAPPINGS_DIR / "lenses" / "tx_features.lens.json"                            # both lenses (tx and kyc): views that declare keys
ONTOP_PROPS = CONFIG_DIR / "ontop-duckdb.properties"                         # the connection to the read-only database
ONTOP_MEMORY_PROPS = CONFIG_DIR / "ontop-memory.properties"                  # in-memory DuckDB, for the typology CSV route
ONTOP_SH = TOOLS / "ontop.sh"

# ---- 6  Validation
SHAPES = VALIDATION_DIR / "shapes" / "t0039.shapes.ttl"
SKELETONS = VALIDATION_DIR / "shapes" / "t0039.skeletons.ttl"
REGISTRY = VALIDATION_DIR / "indicator_registry.json"

# ---- runtime configuration
QUERY_VARS = MAPPING_DIR / "query_vars.ttl"                             # term -> variable name of the pivoted rows

# ---- generated (git-ignored or rebuilt on demand; never edited by hand)
ALIGNMENT = GEN / "typology_alignment.ttl"                      # src/typology.py: requirements + term sources + realises, as facts for Ontop
DATA_ONTOLOGY_MERGED = GEN / "data_ontology_merged.ttl"
DATA_MAPPING_MERGED = GEN / "data.r2rml.ttl"
UNIFIED_MAPPING = GEN / "unified.r2rml.ttl"
UNIFIED_ONTOLOGY = GEN / "unified_ontology.ttl"
UNIFIED_PROPS = GEN / "unified.properties"
TYPOLOGY_TBOX = GEN / "typology_tbox.ttl"
TYPOLOGY_MERGED = GEN / "typology_merged.ttl"


def rel(path):
    """The path relative to the repository root, as a string: what Ontop is given."""
    return str(Path(path).relative_to(ROOT))
