"""Write generated/amltrix.r2rml.ttl: an R2RML mapping that reads the AMLTRIX beta.4 CSVs (vendor/amltrix/) directly.

Run:  .venv/bin/python src/build_amltrix_mapping.py
The mapping follows the AMLO schema (ontology/amlo.ttl) and the same IRI rules as scripts/build_abox.py:
  - IRI = https://example.org/amltrix/<external id>; an id that appears more than once in a table (beta.4 gives T0098 to two
    techniques) gets the first 8 characters of the STIX UUID appended;
  - sub-techniques are typed amlo:SubTechnique only (Ontop adds amlo:Technique through the subclass axiom) and get skos:broader;
  - one direct property per relationship type. Not mapped: the Link nodes (edge text) and dct:created / dct:modified / aliases /
    URLs: the questions of this project do not use them.
DuckDB reads the CSVs through read_csv() inside the mapping's SQL, so no database file is needed (config/ontop/ontop-memory.properties).
Derived from AMLTRIX by UAB Amlyze (https://framework.amltrix.com), used under the AMLTRIX License Terms. Not endorsed by AMLTRIX.
Derivative works must keep this attribution and be distributed under the same terms.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paths  # noqa: E402

ROOT = paths.ROOT
OUT = paths.TYPOLOGY_CSV_MAPPING
VERSION = "1.0-beta.4"


def csv(name):
    return f"read_csv('vendor/amltrix/amltrix-ml-{VERSION}-{name}.csv', header=true, all_varchar=true)"


# table -> (amlo class, name column, id column)
CATALOGUES = {
    "tactics": ("Tactic", "Tactic Name", "external_id"),
    "techniques": ("Technique", "Technique Name", "External ID"),
    "indicators": ("Indicator", "Indicator Name", "Indicator Name"),
    "mitigations": ("Mitigation", "Mitigation Name", "External ID"),
    "actors": ("Actor", "Actor Name", "External ID"),
    "value-instruments": ("ValueInstrument", "Instrument Name", "External ID"),
    "products-service": ("ProductService", "Product/Service Name", "External ID"),
    "datasources": ("DataSource", "Data Source Name", "External ID"),
    "risks": ("RiskType", "Risk Name", "External ID"),
}
# relationship type -> (direct property, table of the non-technique end); technique is the Source for the last two
RELATIONS = {
    "is-achieved-by": ("isAchievedBy", "tactics"),
    "mitigates": ("mitigates", "mitigations"),
    "engages-in": ("engagesIn", "actors"),
    "is-used-by": ("isUsedBy", "value-instruments"),
    "is-exploited-by": ("isExploitedBy", "products-service"),
    "is-associated-with": ("isAssociatedWith", "risks"),
    "is-identified-in": ("isIdentifiedIn", "datasources"),
    "is-indicated-by": ("isIndicatedBy", "indicators"),
}
TECHNIQUE_IS_SOURCE = {"is-identified-in", "is-indicated-by"}


def catalogue_sql(table):
    cls, name, ident = CATALOGUES[table]
    extra = ', "Is Subtechnique" AS sub, "Parent Technique" AS parent' if table == "techniques" else ""
    # computed columns are wrapped in CAST(.. AS VARCHAR): without it Ontop's parser cannot type them and drops the column
    return (f'SELECT "STIX ID" AS stix, '
            f'CAST(CASE WHEN COUNT(*) OVER (PARTITION BY "{ident}") > 1 '
            f'THEN "{ident}" || \'-\' || substr(split_part("STIX ID", \'--\', 2), 1, 8) ELSE "{ident}" END AS VARCHAR) AS iri_id, '
            f'"{ident}" AS eid, "{name}" AS label, CAST(NULLIF(TRIM("Description"), \'\') AS VARCHAR) AS descr{extra} '
            f'FROM {csv(table)}')


HEAD = '''@prefix rr:   <http://www.w3.org/ns/r2rml#> .
@prefix amlo: <https://example.org/amlo#> .
@prefix skos: <http://www.w3.org/2004/02/skos/core#> .
@prefix map:  <https://example.org/mapping/amltrix#> .

# GENERATED by src/build_amltrix_mapping.py from the AMLTRIX beta.4 CSVs: edit the script, not this file.
# Derived from AMLTRIX by UAB Amlyze (https://framework.amltrix.com), used under the AMLTRIX License Terms.
# Not endorsed by AMLTRIX. Derivative works must keep this attribution and be distributed under the same terms.

'''

IRI = "https://example.org/amltrix/{%s}"


def literal_maps():
    return '''  rr:predicateObjectMap [ rr:predicate skos:notation ; rr:objectMap [ rr:column "eid" ] ] ;
  rr:predicateObjectMap [ rr:predicate skos:prefLabel ; rr:objectMap [ rr:column "label" ; rr:language "en" ] ] ;
  rr:predicateObjectMap [ rr:predicate skos:definition ; rr:objectMap [ rr:column "descr" ; rr:language "en" ] ] ;
  rr:predicateObjectMap [ rr:predicate amlo:stixId ; rr:objectMap [ rr:column "stix" ] ] '''


def catalogue_map(table, cls, where=None, name=None, extra=""):
    sql = catalogue_sql(table)
    if where:
        # columns spelled out: Ontop's parser does not expand SELECT * over a derived table
        sql = f"SELECT stix, iri_id, eid, label, descr, sub, parent FROM ({sql}) c WHERE {where}"
    return (f'map:{name or cls} a rr:TriplesMap ;\n'
            f'  rr:logicalTable [ rr:sqlQuery """{sql}""" ] ;\n'
            f'  rr:subjectMap [ rr:template "{IRI % "iri_id"}" ; rr:class amlo:{cls} ] ;\n'
            f'{literal_maps()}{extra}.\n\n')


def broader_map():
    t = catalogue_sql("techniques")   # derived tables, not WITH: Ontop's SQL parser does not accept a leading WITH
    sql = f'SELECT s.iri_id AS s, p.iri_id AS p FROM ({t}) s JOIN ({t}) p ON s.parent = p.stix WHERE s.sub = \'True\'' 
    return ('map:SubTechniqueBroader a rr:TriplesMap ;\n'
            f'  rr:logicalTable [ rr:sqlQuery """{sql}""" ] ;\n'
            f'  rr:subjectMap [ rr:template "{IRI % "s"}" ] ;\n'
            f'  rr:predicateObjectMap [ rr:predicate skos:broader ; rr:objectMap [ rr:template "{IRI % "p"}" ] ] .\n\n')


def relation_map(rtype):
    prop, other = RELATIONS[rtype]
    src, tgt = ("techniques", other) if rtype in TECHNIQUE_IS_SOURCE else (other, "techniques")
    sql = (f'SELECT a.iri_id AS s, b.iri_id AS o FROM {csv("relationships")} r '
           f'JOIN ({catalogue_sql(src)}) a ON r."Source" = a.stix JOIN ({catalogue_sql(tgt)}) b ON r."Target" = b.stix '
           f'WHERE r."Relationship Type" = \'{rtype}\'')
    return (f'map:rel_{prop} a rr:TriplesMap ;\n'
            f'  rr:logicalTable [ rr:sqlQuery """{sql}""" ] ;\n'
            f'  rr:subjectMap [ rr:template "{IRI % "s"}" ] ;\n'
            f'  rr:predicateObjectMap [ rr:predicate amlo:{prop} ; rr:objectMap [ rr:template "{IRI % "o"}" ] ] .\n\n')


def main():
    out = HEAD
    for table, (cls, _, _) in CATALOGUES.items():
        if table == "techniques":
            out += catalogue_map(table, "Technique", where="sub = 'False'")
            out += catalogue_map(table, "SubTechnique", where="sub = 'True'")
        else:
            out += catalogue_map(table, cls)
    out += broader_map()
    for rtype in RELATIONS:
        out += relation_map(rtype)
    OUT.write_text(out, encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {out.count('a rr:TriplesMap')} triples maps")


if __name__ == "__main__":
    main()
