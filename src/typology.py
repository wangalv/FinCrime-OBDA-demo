"""The AML typology (AMLO + AMLTRIX) read through Ontop, for the demo page.

What Ontop is asked, and what it answers from where:
  - technique, tactic, the indicators of T0039 and their text   <- the AMLTRIX CSVs, through generated/amltrix.r2rml.ttl;
    the tactic is asked as amlo:achievesTactic, which the data only holds as amlo:isAchievedBy (AMLO's inverseOf does the rest)
  - what each indicator needs (align:needsTerm) and which data terms exist (align:DataTerm)   <- generated/typology_alignment.ttl,
    facts in the ontology file. This is OUR reading (draft), generated from ontology/application/typology_requirements.ttl (the source of truth for needs)
    and ontology/alignment/source_vocabulary.ttl and aml_data_alignment.ttl, so it cannot drift from them. AMLTRIX itself does not say which data an indicator needs.
  - "which needs are missing" is a SPARQL FILTER NOT EXISTS over those two, not code.
src/indicators.py still decides the answers shown to the investigator; check() compares this route with it.

Run with the project venv:  .venv/bin/python src/typology.py   (rebuilds the alignment file, asks Ontop, prints the table and the check)
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import data_ontology  # noqa: E402
import indicators  # noqa: E402
import sources  # noqa: E402
import typology_ontop as T  # noqa: E402

ALIGN_PREFIX = "PREFIX align: <https://example.org/align#>\n"

HEAD = '''@prefix owl:   <http://www.w3.org/2002/07/owl#> .
@prefix rdfs:  <http://www.w3.org/2000/01/rdf-schema#> .
@prefix align: <https://example.org/align#> .
@prefix amx:   <https://example.org/amltrix/> .
@prefix fcd:   <https://example.org/fincrime-data#> .
@prefix amd:   <https://example.org/aml-data#> .

# GENERATED by src/typology.py from ontology/application/typology_requirements.ttl (needs) and src/data_ontology.py (the terms the data can speak about): edit those, not this file.
# DRAFT by Claude, 2026-11-08: which data terms an indicator needs is our reading; AMLTRIX does not say. Not reviewed by a domain expert.
# Facts in an ontology file are read by Ontop only for properties/classes the ontology declares, hence the declarations here.

align:needsTerm a owl:ObjectProperty ; rdfs:comment "The indicator needs this term of the data ontology to be checked." .
align:backgroundTerm a owl:ObjectProperty ; rdfs:comment "The technique's investigator background: a term to show, not evidence for any indicator." .
align:recordedIn a owl:ObjectProperty ; rdfs:comment "The AML term is recorded in this data source of the typology (ontology/application/typology_requirements.ttl)." .
align:realisesSource a owl:ObjectProperty ; rdfs:comment "The table behind this triples map provides this data source of the typology (mappings/transaction/tx_features.r2rml.ttl, customer.r2rml.ttl)." .
align:DataTerm a owl:Class ; rdfs:comment "A term the data can speak about: a data term (ontology/alignment/source_vocabulary.ttl), or an AML term with a data term under it in the alignment (ontology/alignment/aml_data_alignment.ttl)." .

'''


def short(iri):
    return data_ontology.short(iri)


def build_alignment():
    reg, terms = indicators.registry(), sorted(indicators.available_terms())
    out = HEAD + "".join(f"{t} a align:DataTerm .\n" for t in terms) + "\n"
    for ind in reg["indicators"]:
        out += f"amx:{ind['id']} align:needsTerm " + " , ".join(ind["needs"]) + " .\n"
    out += f"amx:{reg['technique']} align:backgroundTerm " + " , ".join(indicators.background(reg["technique"])) + " .\n"
    # the data source layer: where each AML term is recorded, and which source each table (triples map) provides
    out += "\n" + "".join(f"{t} align:recordedIn " + " , ".join(f"amx:{d}" for d in ds) + " .\n" for t, ds in sorted(sources.recorded_in().items()))
    out += "".join(f"<https://example.org/obda/tx_features#{m['map']}> align:realisesSource amx:{ds} .\n"
                   for ds, maps in sorted(sources.realises().items()) for m in maps)
    new = out
    if not T.ALIGNMENT.exists() or T.ALIGNMENT.read_text(encoding="utf-8") != new:
        T.ALIGNMENT.write_text(new, encoding="utf-8")
    return T.ALIGNMENT


OVERVIEW = """SELECT ?technique ?tactic ?ind ?text ?need WHERE {
  amx:%(tech)s skos:prefLabel ?technique ; amlo:achievesTactic ?tac ; amlo:isIndicatedBy ?i .
  ?tac skos:prefLabel ?tactic .
  ?i skos:prefLabel ?ind ; skos:definition ?text .
  OPTIONAL { ?i align:needsTerm ?need }
} ORDER BY ?ind ?need"""

MISSING = """SELECT ?ind ?need WHERE {
  amx:%(tech)s amlo:isIndicatedBy ?i .
  ?i skos:prefLabel ?ind ; align:needsTerm ?need .
  FILTER NOT EXISTS { ?need a align:DataTerm }
} ORDER BY ?ind ?need"""

SOURCES = """SELECT ?d ?name ?kind ?v WHERE {
  amx:%(tech)s amlo:isIdentifiedIn ?d . ?d skos:prefLabel ?name .
  { BIND("source" AS ?kind) BIND(?d AS ?v) }
  UNION { BIND("term" AS ?kind) ?v align:recordedIn ?d }
  UNION { BIND("missing" AS ?kind) ?v align:recordedIn ?d . FILTER NOT EXISTS { ?v a align:DataTerm } }
  UNION { BIND("map" AS ?kind) ?v align:realisesSource ?d }
}"""

_cache = {}


def _ask(sparql):
    rows, secs, err = T.run_ontop(ALIGN_PREFIX + sparql, "aligned")
    return rows, secs, err


def read(force=False):
    """Ask Ontop (cached for the life of the process). Returns a dict, never raises; 'error' is set when Ontop failed."""
    if _cache and not force:
        return _cache["t"]
    reg = indicators.registry()
    q = {"overview": OVERVIEW % {"tech": reg["technique"]}, "missing": MISSING % {"tech": reg["technique"]},
         "sources": SOURCES % {"tech": reg["technique"]}}
    res = {"technique_id": reg["technique"], "sparql": q, "error": None, "seconds": 0.0, "indicators": [], "technique": None, "tactic": None,
           "sources": [], "check": {"ok": False, "problems": ["not run"]}}
    try:
        build_alignment()
        over, s1, e1 = _ask(q["overview"])
        miss, s2, e2 = _ask(q["missing"])
        srows, s3, e3 = _ask(q["sources"])
    except Exception as e:  # noqa: BLE001 - the page must go on without the typology
        res["error"] = f"{type(e).__name__}: {e}"
        return res
    res["seconds"] = round(s1 + s2 + s3, 1)
    if e1 or e2 or e3:
        res["error"] = (e1 or e2 or e3)[-300:]
        _cache["t"] = res
        return res
    by_id = {}
    for technique, tactic, ind, text, need in over:
        res["technique"], res["tactic"] = technique, tactic
        e = by_id.setdefault(ind, {"id": ind, "text": text, "needs": [], "missing": []})
        if need:
            e["needs"].append(short(need))
    for ind, need in miss:
        by_id[ind]["missing"].append(short(need))
    for e in by_id.values():
        have = [n for n in e["needs"] if n not in e["missing"]]
        e["answerability"] = "answerable" if not e["missing"] else ("partial" if have else "unanswerable")
    res["indicators"] = [by_id[k] for k in sorted(by_id)]
    res["sources"] = _sources_from(srows)
    res["check"] = check(res)
    _cache["t"] = res
    return res


def _sources_from(rows):
    """The per-source table from what Ontop returned (kinds: source, term, missing, map): same shape as sources.derive()."""
    ids, nm, recorded, missing, realised = [], {}, {}, set(), {}
    tables = {m["map"]: m["table"] for lst in sources.realises().values() for m in lst}
    for d, name, kind, v in rows:
        ds = d[len(sources.AMX):]
        if kind == "source":
            ids.append(ds)
            nm[ds] = name
        elif kind == "term":
            recorded.setdefault(short(v), []).append(ds)
        elif kind == "missing":
            missing.add(short(v))
        elif kind == "map":
            m = v.rsplit("#", 1)[-1]
            realised.setdefault(ds, []).append({"map": m, "table": tables.get(m)})
    covered = {t for t in recorded if t not in missing}
    return sources.build(sorted(set(ids)), {t: sorted(set(v)) for t, v in recorded.items()},
                         {k: sorted(v, key=lambda x: x["map"]) for k, v in realised.items()}, covered, nm)


def _norm(s):
    return re.sub(r"\s+", " ", s or "").strip()


def check(res):
    """Compare what Ontop read with the registry and indicators.py. Returns {'ok', 'problems'}."""
    reg, terms = indicators.registry(), indicators.available_terms()
    problems = []
    got = {e["id"]: e for e in res["indicators"]}
    if set(got) != {i["id"] for i in reg["indicators"]}:
        problems.append(f"indicator ids differ: Ontop {sorted(got)} vs registry {sorted(i['id'] for i in reg['indicators'])}")
    for ind in reg["indicators"]:
        e = got.get(ind["id"])
        if not e:
            continue
        if _norm(e["text"]) != _norm(ind["text"]):
            problems.append(f"{ind['id']}: text in AMLTRIX differs from the registry")
        if sorted(e["needs"]) != sorted(ind["needs"]):
            problems.append(f"{ind['id']}: needs differ ({sorted(e['needs'])} vs {sorted(ind['needs'])})")
        ans, missing = indicators.answerability(ind, terms)
        if e["answerability"] != ans or sorted(e["missing"]) != sorted(missing):
            problems.append(f"{ind['id']}: Ontop says {e['answerability']} (missing {e['missing']}), code says {ans} (missing {missing})")
    # the data source layer: what Ontop read against the same chain read in python, and the declarations against each other
    want = {x["id"]: x for x in sources.derive(reg["technique"])}
    got_s = {x["id"]: x for x in res.get("sources", [])}
    if set(got_s) != set(want):
        problems.append(f"data sources differ: Ontop {sorted(got_s)} vs the typology files {sorted(want)}")
    for ds, w in want.items():
        g = got_s.get(ds)
        if g and (g["state"], g["terms"], g["missing"], [m["map"] for m in g["realised_by"]]) != (
                w["state"], w["terms"], w["missing"], [m["map"] for m in w["realised_by"]]):
            problems.append(f"{ds}: Ontop says {g['state']} {g['missing']}, the python reading says {w['state']} {w['missing']}")
    problems += sources.check(reg["technique"], {i["id"]: i["needs"] for i in reg["indicators"]})
    return {"ok": not problems, "problems": problems}


def sentence(res):
    """One line for the chat log."""
    if res["error"]:
        return f"AML typology · Ontop could not read it: {res['error'][:120]}"
    n = len(res["indicators"])
    c = {k: sum(1 for e in res["indicators"] if e["answerability"] == k) for k in ("answerable", "partial", "unanswerable")}
    st = {k: sum(1 for x in res.get("sources", []) if x["state"] == k) for k in ("available", "partial", "background_only", "none")}
    src = (f"; of its {len(res.get('sources', []))} data sources this database has {st['available'] + st['partial']} (in full or in part), "
           f"{st['background_only']} as background only, {st['none']} not at all") if res.get("sources") else ""
    return (f"AML typology · Ontop read AMLTRIX: {res['technique_id']} {res['technique']} ({res['tactic']}) has {n} indicators; "
            f"the data can fully answer {c['answerable']}, partly {c['partial']}, not at all {c['unanswerable']}{src}"
            + ("" if res["check"]["ok"] else f" (check against the code FAILED: {res['check']['problems'][0][:100]})"))


def main():
    res = read(force=True)
    print(sentence(res), f"[{res['seconds']} s]")
    for e in res["indicators"]:
        print(f"  {e['id']}  {e['answerability']:12} needs {e['needs']}" + (f"  missing {e['missing']}" if e["missing"] else ""))
    print("check against indicators.py:", "ok" if res["check"]["ok"] else res["check"]["problems"])
    return 0 if res["check"]["ok"] and not res["error"] else 1


if __name__ == "__main__":
    sys.exit(main())
