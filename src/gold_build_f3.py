"""F3 gold: account context for the transactions an investigator gives ("who are these customers?").

Run with the AML Triage venv:  "../AML Triage Demo/.venv/bin/python" src/gold_build_f3.py
Reads the accepted F1 gold (gold/cases.json, unchanged) for transaction ids; writes gold/cases_f3.json.
No random choice: the F1 cases below are listed by id. Context comes from kyc_profiles, which is SYNTHETIC (generated by AML Triage,
not IBM data); it is context for the investigator, not evidence for any T0039 indicator.
"""
import json
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT.parent / "AML Triage Demo" / "data" / "features.duckdb"
F1 = json.loads((ROOT / "gold" / "cases.json").read_text(encoding="utf-8"))["cases"]
FROM_F1 = ["F1-loop3-01", "F1-loop3-03", "F1-loop4-01", "F1-loop4-02", "F1-loop3-unlabelled-01", "F1-chain-01", "F1-roundtrip"]
PREFIX = "PREFIX fcd: <https://example.org/fincrime-data#>"
WORDINGS = [
    "Who are the customers behind the accounts in transactions {ids}?",
    "For transactions {ids}, tell me what kind of customers the accounts belong to: type, industry, how long open, PEP, risk rating.",
    "I am looking at transactions {ids}. Give me the KYC background of the accounts involved.",
    "Please list the customer profile of every account that sends or receives in {ids}.",
    "What do we know about the account holders in transactions {ids}?",
    "Are any of the accounts in {ids} companies, PEPs or rated high risk?",
    "交易 {ids} 涉及的账户分别是什么类型的客户？",
    "请给出交易 {ids} 里每个账户的客户背景（类型、行业、开户天数、PEP、风险等级）。",
]


def sparql(ids):
    return (f"{PREFIX}\nSELECT DISTINCT ?account ?customerType ?industry ?tenure ?pep ?risk WHERE {{\n"
            f"  VALUES ?txid {{ {' '.join(map(str, ids))} }}\n"
            f"  ?tx a fcd:Transaction ; fcd:txId ?txid .\n"
            f"  {{ ?tx fcd:fromAccount ?account }} UNION {{ ?tx fcd:toAccount ?account }}\n"
            f"  ?account fcd:customerType ?customerType ; fcd:onboardingTenureDays ?tenure ; fcd:pepFlag ?pep ; fcd:riskRating ?risk .\n"
            f"  OPTIONAL {{ ?account fcd:industry ?industry }}\n}}")


def sql(ids):
    lst = ", ".join(map(str, ids))
    return ("SELECT account_id, customer_type, NULLIF(industry, '') AS industry, onboarding_tenure_days, pep_flag, risk_rating "
            "FROM kyc_profiles WHERE account_id IN (SELECT from_account FROM tx_features WHERE tx_id IN (" + lst + ") "
            "UNION SELECT to_account FROM tx_features WHERE tx_id IN (" + lst + ")) ORDER BY account_id")


def main():
    con = duckdb.connect(str(DB), read_only=True)
    byid = {c["id"]: c for c in F1}
    cases = []
    for fid in FROM_F1:
        ids = byid[fid]["tx_ids"]
        rows = [dict(zip(["account", "customer_type", "industry", "tenure", "pep", "risk"], r))
                for r in con.execute(sql(ids)).fetchall()]
        cases.append({
            "id": "F3-" + fid.removeprefix("F1-"), "family": "F3", "role": "context", "from_f1_case": fid,
            "what": "Customer background (synthetic KYC) of every account that sends or receives in the given transactions.",
            "tx_ids": ids, "gold_sparql": sparql(ids), "gold_sql": sql(ids), "gold_rows": rows,
            "questions": [w.format(ids=", ".join(map(str, ids))) for w in WORDINGS],
            "review": "written by Claude; not reviewed by the user or a domain expert",
        })
    out = {"meta": {"database": "AML Triage Demo/data/features.duckdb (tx_features, kyc_profiles)",
                    "note": "kyc_profiles is synthetic. onboarding_tenure_days is a random draw with no reference date. Context only: no T0039 indicator uses it.",
                    "status": "DRAFT. Not reviewed by the user. Freeze before any model run; log every later change."},
           "cases": cases}
    (ROOT / "gold" / "cases_f3.json").write_text(json.dumps(out, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    for c in cases:
        kinds = sorted({(r["customer_type"], r["industry"] or "-") for r in c["gold_rows"]})
        print(c["id"], len(c["gold_rows"]), "accounts", kinds)


main()
